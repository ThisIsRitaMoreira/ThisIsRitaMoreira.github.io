"""results.json from run_local.py -> data/fabric_lakehouse.js for the portfolio (chapter 11 of the airline capsule).

Usage:  python -I fabric/tools/export_results.py <results.json> data/fabric_lakehouse.js <local|fabric>
'fabric' marks the figures as confirmed by a run in Microsoft Fabric (same notebooks, same data).
"""
import json
import sys
from pathlib import Path

src, out, where = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
assert where in ("local", "fabric")
r = json.loads(src.read_text(encoding="utf-8"))
data = {
    "where": where,
    "engine": r["engine"],
    "tables": r["tables"],
    "ingest_log": [{k: x[k] for k in ("_source_file", "rows", "rows_as_ha", "carriers")} for x in r["ingest_log"]],
    "dq_checks": r["dq_checks"],
    "reconciliation": r["reconciliation"],
}
out.write_text("/* generated by fabric/tools/export_results.py: do not edit by hand */\n"
               f"window.DATA_FABRIC = {json.dumps(data, separators=(',', ':'), ensure_ascii=False)};\n",
               encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size} bytes)")
